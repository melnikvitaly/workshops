#ifndef CONFIG_H
#define CONFIG_H

/* ============================================================================
 *  Config — усі налаштування прошивки в одному місці
 * ============================================================================
 *  Тут зібрано те, що зазвичай хочеться підкрутити: адреси, розкладку екрана,
 *  періоди. Логіка лишається в *.h драйверах та в main.c.
 *
 *  Адреси RTC/EEPROM лишаються у своїх драйверах (DS1307_ADDR, EEPROM_ADDR),
 *  бо жорстко зашиті в мікросхемах; тут — те, що стосується прикладного рівня.
 * ============================================================================ */

/* --- Параметри OLED-дисплея --- */
#define OLED_ADDR    0x3C   /* 7-бітна адреса SSD1306 на шині I2C */
#define OLED_WIDTH   128
#define OLED_HEIGHT  64

/* --- Розкладка кадру ---
 * Чотири рядки по центру, зверху вниз (екран 64 рядки). Великим шрифтом те, на
 * що дивляться, дрібним — довідкове:
 *     годинник   scale 2 -> рядки  0..13   "12:34:56"
 *     адреси I2C scale 1 -> рядки 18..24   "0x3C 0x50 0x68"
 *     світло     scale 2 -> рядки 30..43   "L1003"
 *     темпи      scale 1 -> рядки 50..56   "P3 B124928"
 * Висота рядка = 7 * scale, тож нижня межа = Y + 7*SCALE - 1 (має бути <= 63).
 * Ширина = 6 * scale на символ (максимум 21 символ при scale 1). */
#define CLOCK_Y         0    /* годинник у верхньому рядку */
#define DEVICES_Y       18   /* адреси під годинником */
#define LIGHT_Y         30   /* поточне значення АЦП світла — великим шрифтом */
#define RATES_Y         50   /* темпи: пакетів/с та байтів/с через DMA */
#define CLOCK_SCALE     2    /* 10x14 пікселів на символ */
#define DEVICES_SCALE   1    /* дрібний шрифт для адрес */
#define LIGHT_SCALE     2    /* 10x14 — світло видно здалеку */
#define RATES_SCALE     1    /* дрібний шрифт для лічильників */

/* --- Сканування шини I2C --- */
#define SCAN_PERIOD_MS      10000  /* сканувати шину раз на 10 секунд */
#define MAX_DEVICES_SHOWN   4      /* скільки адрес влазить на екран */

/* --- Розміри текстових буферів --- */
#define DEVICES_STR_LEN     32
#define CLOCK_STR_LEN       16
#define LIGHT_STR_LEN       12   /* "L4095" + запас */
#define RATES_STR_LEN       24   /* "P99 B125000" + запас */

/* --- Періоди головного циклу --- */
#define FRAME_PERIOD_MS     1000   /* оновлювати кадр раз на секунду */

/* Період логування освітлення в EEPROM (1 година = 60*60*1000 мс).
 * ⚠️ ПОРАДА: для перевірки роботи на уроці змініть на 5000 (5 секунд). */
#define LOG_INTERVAL_MS     3600000

/* --- Потокове зчитування світла: ADC + TIM2 + циклічний DMA --- */
/* Частоту вибірок задає TIM2 у CubeMX (Prescaler/Period; зараз 16МГц/1600/50 =
 * 200 Гц). Половина буфера усереднюється в один запис "LGHT", тож темп записів у
 * SPI-потік = 2 * SAMPLE_RATE / ADC_BUF_LEN = 200/(200/2) = 2 записи/с — досить
 * повільно, щоб майстер устигав вичитувати кільце. LIGHT_SAMPLE_RATE_HZ тут лише
 * довідково (щоб перерахувати темп); реальне значення — у налаштуваннях TIM2. */
#define LIGHT_SAMPLE_RATE_HZ  200   /* довідково: має збігатися з TIM2 у CubeMX */
#define LIGHT_ADC_BUF_LEN     200   /* розмір циклічного DMA-буфера (вибірок) */

/* --- Потокове зчитування часу з RTC --- */
/* Як часто (мс) зчитувати DS1307 і класти запис "TIME" у SPI-потік. */
#define RTC_STREAM_INTERVAL_MS  1000

#endif /* CONFIG_H */
