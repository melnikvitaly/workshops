#ifndef LIGHT_ARCHIVE_H
#define LIGHT_ARCHIVE_H

#include "stm32f4xx_hal.h"

/* ============================================================================
 *  LightArchive — журнал освітлення у зовнішній EEPROM (AT24Cxx, 0x50)
 * ============================================================================
 *  Раз на LOG_INTERVAL_MS (config.h) бере останнє усереднене значення світла в
 *  відсотках у sensor_stream і дописує один байт у EEPROM. Вказівник наступного
 *  запису зберігається в самій пам'яті (перші два байти), тож журнал переживає
 *  перезавантаження.
 *
 *  Це саме архів: миттєві значення йдуть у SPI-потік ("LGHT"/"TIME", див.
 *  log_emission.h), а сюди лягає одна точка на годину — по байту на вибірку.
 * ============================================================================ */

/* Прочитати з EEPROM вказівник наступного запису. Викликати один раз після
 * ініціалізації I2C (шина має бути вже піднята). */
void LightArchive_Init(I2C_HandleTypeDef *hi2c);

/* Неблокуюча перевірка таймера: якщо минув LOG_INTERVAL_MS — дописати один
 * байт освітлення. Викликати щоітерації головного циклу. */
void LightArchive_Poll(void);

#endif /* LIGHT_ARCHIVE_H */
