#ifndef DISPLAY_UI_H
#define DISPLAY_UI_H

#include "stm32f4xx_hal.h"

/* ============================================================================
 *  DisplayUI — кадр на OLED-дисплеї (SSD1306, 0x3C)
 * ============================================================================
 *  Єдиний власник дисплея і всього, що на ньому видно. Раз на FRAME_PERIOD_MS
 *  збирає чотири рядки й перемальовує кадр:
 *      годинник   — час з DS1307
 *      адреси I2C — результат сканування шини (раз на SCAN_PERIOD_MS)
 *      світло     — сире значення АЦП з sensor_stream
 *      темпи      — пакети/с, збої I2C і кілобіти/с з log_emission
 *  Розкладку (Y, масштаб, періоди) задано в config.h.
 *
 *  Дані тільки читає: сенсорів не опитує і в SPI-потік нічого не кладе.
 *  Якщо обмін з дисплеєм зривається, кадр піднімає шину через i2c_bus.h і
 *  пробує переініціалізувати дисплей — по одній спробі на кадр.
 * ============================================================================ */

/* Підняти дисплей на вже ініціалізованій шині I2C. Невдача не фатальна:
 * дисплей позначається неготовим, а DisplayUI_Poll() пробуватиме підняти його
 * раз на кадр (гаряче підключення теж працює). */
void DisplayUI_Init(I2C_HandleTypeDef *hi2c);

/* Неблокуюча перевірка таймерів: сканування шини і перемальовування кадру,
 * кожне у свій період. Викликати щоітерації головного циклу.
 *
 * ⚠️ Сам кадр блокуючий: SSD1306_Flush жене 1 КБ по I2C на 100 кГц (~92 мс),
 * тож головний цикл на цей час стоїть (див. примітку в config.h). */
void DisplayUI_Poll(void);

#endif /* DISPLAY_UI_H */
