#ifndef I2C_BUS_H
#define I2C_BUS_H

#include "stm32f4xx_hal.h"

/* ============================================================================
 *  I2C bus recovery — підняти шину I2C1 після зірваного обміну
 * ============================================================================
 *  Якщо обмін обірвався посеред байта (таймаут без STOP), ламається одразу два
 *  боки: периферія STM32 лишається з піднятим BUSY, а раб — з притиснутою SDA.
 *  Скидання МК не допомагає НІЯК: раб скидання не бачив, тому плата й оживала
 *  лише після зняття живлення з дисплея.
 *
 *  Тут лікуємо обидва боки: 9 тактів ручного клокінгу — чужий бік
 *  (I2CBus_Release), SWRST у HAL_I2C_DeInit — свій (I2CBus_Recover).
 *
 *  Шина зашита на PB6 (SCL) / PB7 (SDA), AF4 — так, як її піднімає
 *  HAL_I2C_MspInit у stm32f4xx_hal_msp.c.
 * ============================================================================ */

/* Звільнити шину, яку тримає завислий раб: перевести SCL/SDA у звичайний GPIO,
 * доклацати до 9 тактів (байт + ACK), доки SDA не відпустять, і видати ручний
 * STOP. Піни лишаються в режимі GPIO — після виклику потрібна ініціалізація
 * I2C-периферії (MX_I2C1_Init / HAL_I2C_Init), щоб повернути їх у AF4.
 *
 * Викликається і на старті (шина могла лишитись захопленою ще з минулого
 * сеансу — раб про скидання МК не знає), і в аварійному відновленні. */
void I2CBus_Release(void);

/* Повний цикл відновлення: SWRST периферії, 9 тактів по шині і повторна
 * ініціалізація hi2c з тими самими параметрами (HAL_I2C_DeInit не чіпає
 * hi2c->Init, тож конфігурацію переініціалізовувати не треба).
 *
 * Повертає статус HAL_I2C_Init: якщо периферія не піднялась, викликач може
 * просто спробувати ще раз наступного разу — на відміну від старту, зависати
 * тут в Error_Handler немає сенсу. */
HAL_StatusTypeDef I2CBus_Recover(I2C_HandleTypeDef *hi2c);

#endif /* I2C_BUS_H */
