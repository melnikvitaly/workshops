#ifndef CONFIG_H
#define CONFIG_H

/* ============================================================================
 *  Config — усі налаштування прошивки в одному місці
 * ============================================================================
 *  Тут зібрано те, що зазвичай хочеться підкрутити: адреси, розкладку екрана,
 *  періоди. Логіка лишається в заголовках-драйверах Inc та в модулях Src.
 *
 *  Адреси RTC/BME280 лишаються у своїх драйверах (DS1307_ADDR, BME280_ADDR_*),
 *  бо жорстко зашиті в мікросхемах; тут — те, що стосується прикладного рівня.
 * ============================================================================ */

/* --- Параметри OLED-дисплея --- */
#define OLED_ADDR    0x3C   /* 7-бітна адреса SSD1306 на шині I2C */
#define OLED_WIDTH   128
#define OLED_HEIGHT  64

/* --- Розкладка кадру ---
 * Шість рядків зверху вниз (екран 64 рядки). Великим шрифтом лише годинник —
 * єдине, на що дивляться здалеку; решта дрібним, бо після BME280 рядків стало
 * шість і на два масштаби-2 місця вже немає:
 *     годинник   scale 2 -> рядки  0..13   "12:34:56"
 *     адреси I2C scale 1 -> рядки 16..22   "0x3C 0x50 0x68 0x76"
 *     T / RH     scale 1 -> рядки 26..32   "T:23.4C RH:45%"
 *     тиск       scale 1 -> рядки 36..42   "P:1013 hPa"
 *     світло     scale 1 -> рядки 46..52   "L1003 61%"
 *     лінк       scale 1 -> рядки 56..62   "TX120 F0 E0"
 * Висота рядка = 7 * scale, тож нижня межа = Y + 7*SCALE - 1 (має бути <= 63).
 * Ширина = 6 * scale на символ (максимум 21 символ при scale 1).
 *
 * ⚠️ Дата на екран не виводиться — час і так видно у верхньому рядку, а місця
 * на шостий рядок немає. По SPI дата йде (див. protocol/telemetry_packet.h). */
#define CLOCK_Y         0    /* годинник у верхньому рядку */
#define DEVICES_Y       16   /* адреси під годинником */
#define ENV_TH_Y        26   /* температура + вологість з BME280 */
#define ENV_P_Y         36   /* тиск з BME280 */
#define LIGHT_Y         46   /* поточне значення АЦП світла + відсотки */
#define RATES_Y         56   /* стан SPI-лінка: відправлено / збоїв */
#define CLOCK_SCALE     2    /* 10x14 пікселів на символ */
#define DEVICES_SCALE   1    /* дрібний шрифт для адрес */
#define ENV_SCALE       1    /* дрібний шрифт для показів BME280 */
#define LIGHT_SCALE     1    /* дрібний шрифт для світла */
#define RATES_SCALE     1    /* дрібний шрифт для лічильників */

/* --- Сканування шини I2C --- */
#define SCAN_PERIOD_MS      10000  /* сканувати шину раз на 10 секунд */
/* RTC + EEPROM + OLED + BME280 — рівно чотири. EEPROM (0x50) сидить на платі
 * Tiny RTC поруч із DS1307 і відповідає на скан, хоча прошивка в неї більше
 * нічого не пише — тому в списку вона є, а в коді її вже немає. */
#define MAX_DEVICES_SHOWN   4

/* --- Розміри текстових буферів --- */
#define DEVICES_STR_LEN     32
#define CLOCK_STR_LEN       16
#define ENV_TH_STR_LEN      24   /* "T:-10.5C RH:100%" + запас */
#define ENV_P_STR_LEN       20   /* "P:1013 hPa" + запас */
#define LIGHT_STR_LEN       16   /* "L4095 100%" + запас */
#define RATES_STR_LEN       24   /* "TX9999 F999 E999" + запас */

/* --- Періоди головного циклу --- */
#define FRAME_PERIOD_MS     1000   /* оновлювати кадр раз на секунду */

/* --- Потокове зчитування світла: ADC + TIM2 + циклічний DMA --- */
/* Частоту вибірок задає TIM2 у CubeMX (Prescaler/Period; зараз 16МГц/1600/50 =
 * 200 Гц). Половина буфера усереднюється в одне значення, тож нове усереднене
 * світло з'являється 20 разів на секунду — з великим запасом для кадру (1 Гц)
 * і для SPI-пакета (1 Гц), які просто беруть останнє значення. */
#define LIGHT_SAMPLE_RATE_HZ  200   /* довідково: має збігатися з TIM2 у CubeMX */
#define LIGHT_ADC_BUF_LEN     20    /* розмір циклічного DMA-буфера (вибірок) */

/* --- Періоди опитування датчиків --- */
/* Як часто (мс) зчитувати DS1307. */
#define RTC_SAMPLE_INTERVAL_MS  1000

/* Як часто (мс) зчитувати BME280. Завдання вимагає не рідше разу на секунду,
 * і саме стільки тут і стоїть. Блокуючого очікування немає: чип працює в
 * NORMAL-режимі зі standby 500 мс і міряє сам, а зчитування — це один обмін по
 * I2C на 8 байтів (~1 мс на 100 кГц). Якщо датчика на шині немає, цей самий
 * таймер раз на секунду пробує підняти його наново (гаряче підключення). */
#define ENV_SAMPLE_INTERVAL_MS  1000

/* --- SPI-лінк до ESP32-C3 --- */
/* Як часто майстер віддає кадр телеметрії рабові. Один кадр = 32 байти на
 * 1 МГц ≈ 256 мкс, тож головний цикл на цей час стоїть — на два порядки менше
 * за блокуюче оновлення екрана поруч (~92 мс), тому окремої оптимізації не
 * потребує. */
#define TELEMETRY_PERIOD_MS     1000

/* Дедлайн одного блокуючого HAL_SPI_Transmit (мс). 32 байти на 1 МГц — це
 * чверть мілісекунди; 100 мс тут лише щоб зависла периферія не заклинила
 * головний цикл назавжди. */
#define TELEMETRY_SPI_TIMEOUT   100

#endif /* CONFIG_H */
