#ifndef CONFIG_H
#define CONFIG_H

/* ============================================================================
 *  Config — усі налаштування прошивки в одному місці
 * ============================================================================
 *  Плата STM32F401CCU6 ("black pill"), та сама розводка, що й у mini-project:
 *
 *      LDR-дільник  -> PA0  (ADC1_IN0)
 *      DS1307 RTC   -> PB6/PB7 (I2C1, адреса 0x68)
 *      AT24C32 EEPROM -> PB6/PB7 (та сама шина I2C1, адреса 0x50)
 *      TTL-USB      -> PA9 (TX МК -> RX конвертера), PA10 (RX МК <- TX)
 *      GND усіх модулів — спільний з платою, живлення 3.3 В (DS1307 на модулі
 *      ZS-042/DS3231-сумісних платах терпить 3.3 В; підтяжки SDA/SCL уже на модулі).
 *
 *  Адреси RTC/EEPROM лишаються у своїх драйверах (DS1307_ADDR, EEPROM_ADDR),
 *  бо жорстко зашиті в мікросхемах; тут — те, що стосується прикладного рівня.
 * ============================================================================ */

/* --- Журнал освітлення --- */
/* Період запису одного рядка журналу в EEPROM.
 * ⚠️ 5 секунд — щоб на уроці одразу було що читати. Для реального журналу
 * ставте 3600000 (година): AT24C32 має 4 КБ, тобто 511 записів по 8 байтів. */
#define LOG_INTERVAL_MS     5000

/* Скільки вибірок АЦП усереднювати в одне значення освітлення. Дільник з
 * фоторезистором високоомний і шумить; вісім вибірок збивають дрижання
 * останніх розрядів і коштують менш ніж мілісекунду. */
#define LIGHT_SAMPLE_COUNT  8

/* Дедлайн одного перетворення АЦП (мс). 480 тактів на 8 МГц ADCCLK — це
 * ~60 мкс, тож 10 мс — з великим запасом на будь-який збій. */
#define LIGHT_ADC_TIMEOUT_MS 10

#define LIGHT_ADC_MAX_RAW   4095u   /* повна шкала 12-бітного АЦП */

/* --- Консоль на TTL-USB (USART1) --- */
#define CONSOLE_BAUDRATE    115200
#define CONSOLE_LINE_LEN    48      /* максимальна довжина команди з монітора порту */
#define CONSOLE_TX_LEN      96      /* буфер одного рядка, що йде в монітор порту */
#define CONSOLE_TX_TIMEOUT  100     /* дедлайн передачі рядка (мс) */

/* ⚠️ Команда виконується по CR або LF, тож монітор порту має надсилати кінець
 * рядка: у Serial Monitor (VS Code) поле "Line ending" -> LF або CRLF, у
 * PlatformIO — `--eol LF`. З "Line ending: None" набране слово просто лежатиме
 * в буфері. */

#endif /* CONFIG_H */
