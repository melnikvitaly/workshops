#ifndef SOFT_TIMER_H
#define SOFT_TIMER_H

#include "stm32f4xx_hal.h"

/* ============================================================================
 *  SoftTimer — програмний таймер періодичних задач на HAL_GetTick
 * ============================================================================
 *  Ідіома всього прикладного рівня: головний цикл нічого не блокує, кожен
 *  модуль щоітерації питає свій таймер і працює лише коли настав його період.
 * ============================================================================ */

/* Чи настав час чергової роботи? Якщо так — записує момент у *lastMs і повертає
 * 1, інакше лишає таймер як є і повертає 0.
 *
 * Перший виклик (*lastMs == 0) спрацьовує одразу — модулю не треба чекати
 * цілий період після старту. Різниця беззнакових мілісекунд рахується правильно
 * і після переповнення лічильника HAL_GetTick (раз на ~49 діб). */
static inline int SoftTimer_Due(uint32_t *lastMs, uint32_t periodMs) {
    const uint32_t now = HAL_GetTick();
    if (*lastMs != 0 && (now - *lastMs) < periodMs) {
        return 0;
    }
    *lastMs = now;
    return 1;
}

#endif /* SOFT_TIMER_H */
