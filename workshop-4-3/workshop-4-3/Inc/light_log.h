#ifndef LIGHT_LOG_H
#define LIGHT_LOG_H

#include "stm32f4xx_hal.h"

/* ============================================================================
 *  LightLog — журнал освітлення з мітками часу в зовнішній EEPROM
 * ============================================================================
 *  Раз на LOG_INTERVAL_MS (config.h) модуль міряє освітлення на PA0, бере час
 *  з DS1307 по I2C і дописує в EEPROM один запис на 8 байтів:
 *
 *      [0] місяць  [1] число  [2] рік     (мм:дд:гг — формат з завдання)
 *      [3] години  [4] хвилини [5] секунди
 *      [6..7] сире 12-бітне значення АЦП, Big-Endian
 *
 *  Вказівник наступного запису живе в самій пам'яті (перші два байти), тож
 *  журнал переживає перезавантаження — саме тому LightLog_Dump() після
 *  ввімкнення показує все, що записалося минулого разу.
 * ============================================================================ */

/* Підхопити вказівник журналу з EEPROM. Викликати один раз після ініціалізації
 * I2C (шина має бути вже піднята). */
void LightLog_Init(I2C_HandleTypeDef *hi2c);

/* Неблокуюча перевірка таймера: якщо минув LOG_INTERVAL_MS — дописати запис
 * і показати його в моніторі порту. Викликати щоітерації головного циклу. */
void LightLog_Poll(void);

/* Прочитати весь журнал з EEPROM і вивести таблицею в монітор порту. */
void LightLog_Dump(void);

/* Почати журнал спочатку (вказівник -> початок даних; самі байти лишаються). */
void LightLog_Clear(void);

/* Поточне освітлення: середнє з LIGHT_SAMPLE_COUNT вибірок АЦП (0..4095). */
uint16_t LightLog_ReadLightRaw(void);

/* Скільки записів уже в журналі. */
uint16_t LightLog_Count(void);

/* Сире значення АЦП у відсотки шкали — лише щоб число легше читалось очима. */
uint8_t LightLog_Percent(uint16_t raw);

#endif /* LIGHT_LOG_H */
