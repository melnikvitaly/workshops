#ifndef CONSOLE_H
#define CONSOLE_H

#include "stm32f4xx_hal.h"

/* ============================================================================
 *  Console — монітор порту через TTL-USB конвертер (USART1, PA9/PA10)
 * ============================================================================
 *  Односторонній вивід (журнал іде в монітор порту рядками) плюс найпростіший
 *  розбір команд, які користувач набирає в тому ж вікні:
 *
 *      help                        — коротка довідка
 *      now                         — поточний час з RTC і поточне освітлення
 *      dump                        — вивести весь журнал з EEPROM
 *      clear                       — почати журнал спочатку
 *      time гг мм дд гг хх сс      — виставити годинник (рік місяць число
 *                                    години хвилини секунди), напр. time 26 8 8 14 30 0
 *
 *  Приймання неблокуюче: щоітерації головного циклу забираємо байти, що вже
 *  прийшли, і збираємо рядок. Передача — блокуюча (HAL_UART_Transmit): рядок у
 *  сотню байтів на 115200 бод — це ~9 мс, і йде він раз на кілька секунд.
 * ============================================================================ */

/* Запам'ятати UART (вивід) і шину I2C (команда "time" пише в RTC),
 * після чого привітатись у монітор порту. */
void Console_Init(UART_HandleTypeDef *huart, I2C_HandleTypeDef *hi2c);

/* Надіслати рядок як є (без додавання переносу). */
void Console_Print(const char *text);

/* Надіслати форматований рядок і перевести каретку ("\r\n" — щоб було охайно
 * і в моніторі PlatformIO, і в PuTTY). */
void Console_Printf(const char *fmt, ...);

/* Забрати прийняті байти й виконати команду, якщо рядок завершено.
 * Викликати щоітерації головного циклу. */
void Console_Poll(void);

#endif /* CONSOLE_H */
